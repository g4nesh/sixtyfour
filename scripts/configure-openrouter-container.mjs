#!/usr/bin/env node

import { randomBytes } from "node:crypto";
import { chmod, mkdir, readFile, rename, stat, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import process from "node:process";

const projectRoot = resolve(process.cwd());
const secretDirectory = resolve(projectRoot, "secrets");
const openRouterSecretPath = resolve(secretDirectory, "openrouter_api_key");
const atlasTokenPath = resolve(secretDirectory, "atlas_api_token");
const environmentPath = resolve(projectRoot, ".env.atlas");
const rotate = process.argv.includes("--rotate");

const ENVIRONMENT_TEMPLATE = `# Generated by npm run container:configure. Contains no provider secret.
ATLAS_LIVE_ENABLED=true
ATLAS_ALLOW_UNAUTHENTICATED_LOCAL=true
LIVE_PROVIDER=openrouter
OPENROUTER_MODEL=openai/gpt-5.4-nano
OPENROUTER_SITE_URL=http://localhost:3000
OPENROUTER_APP_NAME=Atlas
OPENROUTER_API_KEY_FILE=./secrets/openrouter_api_key
ATLAS_API_TOKEN_FILE=./secrets/atlas_api_token
`;

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch (error) {
    if (error && typeof error === "object" && error.code === "ENOENT") return false;
    throw error;
  }
}

async function readSecret() {
  if (!process.stdin.isTTY) {
    let value = "";
    process.stdin.setEncoding("utf8");
    for await (const chunk of process.stdin) {
      value += chunk;
      if (value.length > 4_096) throw new Error("The supplied secret is too long.");
    }
    return value.trim();
  }

  if (typeof process.stdin.setRawMode !== "function") {
    throw new Error("This terminal cannot hide input. Pipe the replacement key through standard input instead.");
  }

  process.stderr.write("Paste the replacement OpenRouter key (input is hidden): ");
  const previousRawMode = process.stdin.isRaw;
  process.stdin.setEncoding("utf8");
  process.stdin.setRawMode(true);
  process.stdin.resume();

  return await new Promise((resolveSecret, rejectSecret) => {
    let value = "";
    let settled = false;

    const cleanup = () => {
      process.stdin.off("data", onData);
      process.stdin.setRawMode(previousRawMode);
      process.stdin.pause();
      process.stderr.write("\n");
    };
    const finish = (error) => {
      if (settled) return;
      settled = true;
      cleanup();
      if (error) rejectSecret(error);
      else resolveSecret(value.trim());
    };
    const onData = (chunk) => {
      for (const character of chunk) {
        if (character === "\u0003") {
          finish(new Error("Configuration canceled."));
          return;
        }
        if (character === "\r" || character === "\n") {
          finish();
          return;
        }
        if (character === "\u007f" || character === "\b") {
          value = [...value].slice(0, -1).join("");
          continue;
        }
        if (character >= " " && value.length < 4_096) value += character;
      }
    };

    process.stdin.on("data", onData);
  });
}

function validateOpenRouterKey(value) {
  if (!/^sk-or-v1-[A-Za-z0-9_-]{32,}$/.test(value)) {
    throw new Error("Expected a replacement OpenRouter API key with the sk-or-v1- prefix.");
  }
}

async function writePrivateFile(path, value) {
  const temporary = `${path}.${process.pid}.tmp`;
  await writeFile(temporary, `${value}\n`, { encoding: "utf8", mode: 0o600, flag: "wx" });
  await rename(temporary, path);
  await chmod(path, 0o600);
}

async function main() {
  await mkdir(secretDirectory, { recursive: true, mode: 0o700 });
  await chmod(secretDirectory, 0o700);

  if ((await exists(openRouterSecretPath)) && !rotate) {
    throw new Error("An OpenRouter secret already exists. Re-run with --rotate to replace it.");
  }

  const existingEnvironment = (await exists(environmentPath)) ? await readFile(environmentPath, "utf8") : null;
  if (existingEnvironment !== null && !/^LIVE_PROVIDER=openrouter$/m.test(existingEnvironment)) {
    throw new Error("Existing .env.atlas is not pinned to LIVE_PROVIDER=openrouter; review it manually.");
  }

  const openRouterKey = await readSecret();
  validateOpenRouterKey(openRouterKey);
  await writePrivateFile(openRouterSecretPath, openRouterKey);

  if (!(await exists(atlasTokenPath))) {
    await writePrivateFile(atlasTokenPath, randomBytes(48).toString("base64url"));
  } else {
    await chmod(atlasTokenPath, 0o600);
  }

  if (!(await exists(environmentPath))) {
    await writeFile(environmentPath, ENVIRONMENT_TEMPLATE, { encoding: "utf8", mode: 0o600, flag: "wx" });
  } else {
    await chmod(environmentPath, 0o600);
  }

  process.stdout.write(
    [
      "OpenRouter container secrets configured.",
      "The provider key was written only to secrets/openrouter_api_key.",
      "Run: npm run container:up",
    ].join("\n") + "\n",
  );
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : "Configuration failed."}\n`);
  process.exitCode = 1;
});
